#!/usr/bin/env python3
"""Write THIRD_PARTY_CRATES.md: every third-party crate in Cargo.lock with its version and SPDX licence.
  scripts/crate-licenses.py            regenerate the file
  scripts/crate-licenses.py --check    exit 1 if the file is out of date
Reads `cargo metadata --offline` (no build, needs the registry sources already downloaded).
The licence is the `license` field of each crate's Cargo.toml. Crates with only a `license-file` are marked.
"""
import json, os, subprocess, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
os.chdir(root)
res = subprocess.run(["cargo", "metadata", "--offline", "--format-version", "1", "--locked"], capture_output=True, text=True, encoding="utf-8")
if res.returncode != 0:
    print(f"crate-licenses: `cargo metadata --offline --locked` failed (exit {res.returncode}); "
          "run `cargo fetch --locked` first, and check that Cargo.lock matches the manifests:\n" + res.stderr, file=sys.stderr)
    sys.exit(1)
meta = json.loads(res.stdout)
members = set(meta["workspace_members"])
rows = sorted(
    (p["name"], p["version"], p["license"] or ("see licence file" if p.get("license_file") else "UNKNOWN"),
     "vendored" if p["source"] is None else "")
    for p in meta["packages"] if p["id"] not in members)
out = [
    "# Third-party Rust crates",
    "",
    "Generated by `scripts/crate-licenses.py` from `Cargo.lock`; do not edit by hand. The licence column is the `license`",
    "field of each crate's `Cargo.toml`. `cargo deny check` (see `deny.toml`) enforces that every crate offers at least one",
    "allowed licence. This list covers all target platforms, including crates that a given build does not compile.",
    "Crates marked vendored live in `vendor/`.",
    "",
    f"{len(rows)} crates.",
    "",
    "| Crate | Version | Licence | |",
    "| --- | --- | --- | --- |",
]
out += [f"| {n} | {v} | {l} | {s} |" for n, v, l, s in rows]
text = "\n".join(out) + "\n"
if "--check" in sys.argv:
    cur = open("THIRD_PARTY_CRATES.md", encoding="utf-8").read() if os.path.exists("THIRD_PARTY_CRATES.md") else ""
    if cur != text:
        print("THIRD_PARTY_CRATES.md is out of date: run scripts/crate-licenses.py", file=sys.stderr)
        sys.exit(1)
else:
    open("THIRD_PARTY_CRATES.md", "w", encoding="utf-8").write(text)
    print(f"THIRD_PARTY_CRATES.md: {len(rows)} crates")
