#!/usr/bin/env python3
"""Write THIRD_PARTY_NPM.md: every npm package the TypeScript SDK pins, with its version and SPDX licence.
  scripts/npm-licenses.py            regenerate the file
  scripts/npm-licenses.py --check    exit 1 if the file is out of date or a licence is not allowed
Reads the lock files only (no network, no node_modules):
  sdk/typescript/toolchain/package-lock.json   what cyx installs to build TypeScript extensions (esbuild,
                                               ComponentizeJS); ComponentizeJS's engine ends up in every TypeScript
                                               extension's component
  sdk/typescript/package-lock.json             the SDK's development dependencies (TypeScript, Node.js types)
The SDK itself has no runtime dependencies. The allowed licences are deny.toml's, plus BlueOak-1.0.0 (permissive, used
by npm's own packages). A package whose lock entry has no licence gets it from KNOWN, checked by hand.
"""
import json, os, re, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
os.chdir(root)
LOCKS = [("sdk/typescript/toolchain/package-lock.json", "build"), ("sdk/typescript/package-lock.json", "dev")]
ALLOWED = {"MIT", "MIT-0", "Apache-2.0", "Apache-2.0 WITH LLVM-exception", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Zlib",
           "Unicode-3.0", "Unlicense", "CC0-1.0", "0BSD", "BSL-1.0", "MPL-2.0", "BlueOak-1.0.0"}
# Packages published without a `license` field; the licence is the LICENSE file in the package.
KNOWN = {"@bytecodealliance/componentize-js": "Apache-2.0 WITH LLVM-exception"}

rows, problems = {}, []
for lock, role in LOCKS:
    packages = json.load(open(lock, encoding="utf-8"))["packages"]
    for path, p in packages.items():
        if not path:
            continue
        # An alias (`"x-0-19-3": "npm:x@0.19.3"`) is the package its tarball names.
        m = re.search(r"registry\.npmjs\.org/(.+?)/-/", p.get("resolved", ""))
        name = m.group(1) if m else path.split("node_modules/")[-1]
        lic = p.get("license") or KNOWN.get(name) or "UNKNOWN"
        key = (name, p["version"])
        roles = rows.setdefault(key, [lic, set()])[1]
        roles.add(role)
        terms = [t.strip("() ") for t in re.split(r"\bOR\b", lic)]
        if not any(t in ALLOWED for t in terms):
            problems.append(f"{name} {p['version']} ({lock}): licence {lic} is not allowed")

out = [
    "# Third-party npm packages",
    "",
    "Generated by `scripts/npm-licenses.py` from the TypeScript SDK's lock files; do not edit by hand. None of these ship",
    "with Codeyard. `build`: what `cyx` installs into its cache folder to build TypeScript extensions",
    "(`sdk/typescript/toolchain`); ComponentizeJS's JavaScript engine, StarlingMonkey (Apache-2.0 WITH LLVM-exception), is",
    "embedded in every TypeScript extension's component. `dev`: the SDK's own development dependencies. The licence column",
    "is the `license` field of each package (from the lock file). Platform packages are listed for every platform.",
    "",
    f"{len(rows)} packages.",
    "",
    "| Package | Version | Licence | Used for |",
    "| --- | --- | --- | --- |",
]
out += [f"| {n} | {v} | {lic} | {', '.join(sorted(r))} |" for (n, v), (lic, r) in sorted(rows.items())]
text = "\n".join(out) + "\n"
if problems:
    print("npm-licenses:\n  " + "\n  ".join(problems), file=sys.stderr)
    sys.exit(1)
if "--check" in sys.argv:
    cur = open("THIRD_PARTY_NPM.md", encoding="utf-8").read() if os.path.exists("THIRD_PARTY_NPM.md") else ""
    if cur != text:
        print("THIRD_PARTY_NPM.md is out of date: run scripts/npm-licenses.py", file=sys.stderr)
        sys.exit(1)
else:
    open("THIRD_PARTY_NPM.md", "w", encoding="utf-8").write(text)
    print(f"THIRD_PARTY_NPM.md: {len(rows)} packages")
